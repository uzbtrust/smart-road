/* Russian writes 51,4 where Uzbek and English write 51.4. Prose strings above
   already carry the right separator; this is for figures rendered from data. */
window.srNum = function (v, lang, decimals) {
  const s = typeof v === "number" ? v.toFixed(decimals == null ? 1 : decimals) : String(v);
  return lang === "ru" ? s.replace(".", ",") : s;
};